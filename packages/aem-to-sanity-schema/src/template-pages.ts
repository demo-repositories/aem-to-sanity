import { readFile } from "node:fs/promises";
import { join } from "node:path";
import {
  writeJson,
  writeTextFile,
  type Logger,
  type PageComponentConfig,
} from "aem-to-sanity-core";
import {
  RESERVED_SANITY_TYPE_NAMES,
  toCamelCase,
  toTitleCase,
} from "./naming.ts";
import { FLAT_PLANNER, type SchemaPathPlanner } from "./layout.ts";
import type { PageBuilderMember } from "./pagebuilder.ts";

/**
 * Marker shared by every file this module writes (per-template document
 * types and their dedicated page-builder arrays). `scanSchemaTypeNames`
 * keys off it to keep these out of `pageBuilder.of[]` in the standalone
 * pagebuilder CLI.
 */
export const TEMPLATE_PAGES_GENERATED_MARKER =
  "GENERATED by aem-to-sanity-schema template-pages";

const GENERATED_MARKER = TEMPLATE_PAGES_GENERATED_MARKER;

export interface TemplatePageManifestEntry {
  /** AEM resource type of the page-shell component (no `/apps/` prefix). */
  pageComponentResourceType: string;
  /** Sanity object type emitted for the page-shell dialog. */
  pageComponentSanityType: string;
  /** Raw `cq:template` path as authored on `jcr:content`. */
  cqTemplate: string;
  /** Sanity document type name emitted for this (resource type, template) pair. */
  sanityType: string;
  /** Studio-facing title for the document type. */
  sanityTitle: string;
  /**
   * The page-builder array type this document references. The shared array
   * (`pageBuilder` by default) unless the entry's `components` map in
   * `aem-page-components.json` restricts components to this template — then
   * a dedicated `{sanityType}Builder` array (base members + this template's
   * extras).
   */
  pageBuilderType: string;
}

export interface TemplatePageManifest {
  __generated: string;
  entries: TemplatePageManifestEntry[];
}

export interface WriteTemplatePageArtifactsOptions {
  /** Directory where schema .ts files are written (same as pageBuilder). */
  schemasDir: string;
  /**
   * Output dir for the cache manifest (`{outputDir}/cache/page-templates.json`).
   * If omitted, the manifest is not written (used by tests that only care
   * about the rendered .ts files).
   */
  manifestOutputDir?: string;
  /** Operator-declared page-shell components → templates pairing. */
  pageComponentsConfig: PageComponentConfig;
  /** Reverse index: AEM resource type → resolved Sanity type name. */
  typeNameByResourceType: Map<string, string>;
  /** Page-builder array type name. Default: "pageBuilder". */
  pageBuilderTypeName?: string;
  /**
   * Members of the shared page-builder array (post-exclusion, as registered
   * in `pageBuilder.of[]`). Required when {@link templateComponents} is
   * non-empty — dedicated per-template arrays are composed as base + extras.
   */
  baseMembers?: PageBuilderMember[];
  /**
   * Template-restricted components, keyed by `cq:template` path — resolved
   * from the `components` maps on `aem-page-components.json` entries. A
   * template with entries here gets its own `{docType}Builder` array type
   * (base members + these extras) instead of referencing the shared
   * page-builder array.
   */
  templateComponents?: ReadonlyMap<string, PageBuilderMember[]>;
  /** Layout planner deciding subfolder placement. Default: flat. */
  planner?: SchemaPathPlanner;
  /**
   * Substitute Sanity type for the `featuredImage` field (e.g.
   * `bynder.asset` when `MIGRATION_ASSET_BACKEND=bynder`); unset → native
   * `image`. Mirrors the component emitter's image/file substitution.
   */
  assetFieldType?: string;
  logger?: Logger;
}

export interface WriteTemplatePageArtifactsResult {
  manifestFile?: string;
  manifest: TemplatePageManifest;
  /** Sanity type names of page-shell objects that should be excluded from pageBuilder.of[]. */
  excludeFromPageBuilder: string[];
  /** Files written for per-template document types. */
  documentFiles: string[];
  /** Files written for dedicated per-template page-builder arrays. */
  builderFiles: string[];
  /**
   * Type names of the dedicated per-template page-builder arrays (one per
   * template that has restricted components). Callers must protect these
   * from the generated-file pruner alongside the document type names.
   */
  builderTypeNames: string[];
  /**
   * Page-shell resource types declared in `aem-page-components.json` that
   * weren't fetched as components (i.e. missing from `aem-component-paths`).
   * Each was skipped — no per-template doc type was emitted for any of its
   * templates. Surfaced so the CLI can log a high-visibility callout.
   */
  missingComponentPaths: string[];
}

/**
 * Convert an AEM `cq:template` path into a stable Sanity type name suffixed
 * with `Page`.
 *
 *   /conf/uxp/settings/wcm/templates/plan-details  → "planDetailsPage"
 *   /conf/.../templates/news-article               → "newsArticlePage"
 *   plan-details                                   → "planDetailsPage"
 *
 * Falls back to the last non-empty segment when no `templates/` marker is
 * found; collisions with built-in Sanity types get the `aem` prefix (same
 * rule `resolveSanityTypeNames` applies to components).
 */
export function templatePathToTypeName(templatePath: string): string {
  const segments = templatePath.split("/").filter(Boolean);
  const marker = segments.lastIndexOf("templates");
  const tail =
    marker >= 0 ? segments.slice(marker + 1) : segments.slice(-1);
  if (tail.length === 0) {
    throw new Error(`Cannot derive type name from cq:template: ${templatePath}`);
  }
  const camel = toCamelCase(tail.join("-"));
  if (!camel) {
    throw new Error(`Cannot derive type name from cq:template: ${templatePath}`);
  }
  return `${camel}Page`;
}

/**
 * Studio-friendly title from a template path. Mirrors the same word-split
 * rules used by `toTitleCase`, with a "Page" suffix so the type's purpose is
 * obvious in the Studio "+ Add" menus and structure list.
 */
export function templatePathToTitle(templatePath: string): string {
  const segments = templatePath.split("/").filter(Boolean);
  const marker = segments.lastIndexOf("templates");
  const tail =
    marker >= 0 ? segments.slice(marker + 1) : segments.slice(-1);
  const base = toTitleCase(tail.join(" "));
  return base ? `${base} Page` : "Page";
}

/**
 * For each (page-component resource type, cq:template) declared in the
 * tenant's `aem-page-components.json`, render one Sanity document type:
 *
 *   defineType({
 *     name: "<template>Page",
 *     type: "document",
 *     fields: [title, slug, tags, pageProperties, featuredImage, cqTemplate, pageBuilder],
 *   })
 *
 * The type name derives from the template path (`templatePathToTypeName`)
 * unless the entry's `names` map pins an explicit name/title for the
 * template — explicit names claim first and are used verbatim; a reserved
 * or colliding explicit name is a hard error.
 *
 * The `pageProperties` field type points at the Sanity object emitted for
 * the page-shell component (resolved through `typeNameByResourceType`),
 * which is the same object the schema emitter produces for every other
 * dialog. Page-shell types are returned in `excludeFromPageBuilder` so the
 * caller can drop them from `pageBuilder.of[]` — they're not blocks.
 *
 * Files are GENERATED-marker guarded the same way `pagebuilder.ts`
 * preserves hand-edits.
 */
export async function writeTemplatePageArtifacts(
  opts: WriteTemplatePageArtifactsOptions,
): Promise<WriteTemplatePageArtifactsResult> {
  const {
    schemasDir,
    manifestOutputDir,
    pageComponentsConfig,
    typeNameByResourceType,
    pageBuilderTypeName = "pageBuilder",
    baseMembers = [],
    templateComponents,
    planner = FLAT_PLANNER,
    assetFieldType,
    logger,
  } = opts;

  const manifest: TemplatePageManifest = {
    __generated: GENERATED_MARKER,
    entries: [],
  };
  const excludeFromPageBuilder = new Set<string>();
  const documentFiles: string[] = [];
  const builderFiles: string[] = [];
  const builderTypeNames: string[] = [];
  const missingComponentPaths: string[] = [];

  if (pageComponentsConfig.size === 0) {
    let manifestFile: string | undefined;
    if (manifestOutputDir) {
      manifestFile = join(manifestOutputDir, "cache", "page-templates.json");
      await writeJson(manifestFile, manifest);
    }
    return {
      manifestFile,
      manifest,
      excludeFromPageBuilder: [],
      documentFiles,
      builderFiles,
      builderTypeNames,
      missingComponentPaths,
    };
  }

  // Resolve every (resourceType, template) pair to a Sanity document name.
  // First pass: gather candidates so we can apply the same collision rules
  // resolveSanityTypeNames uses for components — reserved-name prefix +
  // numeric suffix on duplicates. The page-component object names already
  // exist in `typeNameByResourceType` (taken set seed).
  const taken = new Set<string>(typeNameByResourceType.values());

  // Explicit names from `aem-page-components.json` claim first — same
  // precedence rule `aem-component-names.json` gets for components. A
  // reserved built-in or a collision with an emitted component type is a
  // hard error rather than a silent fallback: the operator asked for that
  // exact `_type`, so anything else would orphan their content.
  for (const entry of pageComponentsConfig.values()) {
    if (!entry.names) continue;
    for (const [template, override] of Object.entries(entry.names)) {
      const name = override.name;
      if (name === undefined) continue;
      if (RESERVED_SANITY_TYPE_NAMES.has(name)) {
        throw new Error(
          `template-pages: explicit name "${name}" (for template "${template}") is a reserved Sanity type name — pick a different name in aem-page-components.json`,
        );
      }
      if (taken.has(name)) {
        throw new Error(
          `template-pages: explicit name "${name}" (for template "${template}") collides with an already-emitted type of the same name — pick a different name in aem-page-components.json`,
        );
      }
      taken.add(name);
    }
  }

  for (const [resourceType, entry] of pageComponentsConfig.entries()) {
    const pageComponentSanityType = typeNameByResourceType.get(resourceType);
    if (!pageComponentSanityType) {
      // No Sanity object type was emitted for this resource type — it's
      // declared as a page-shell in `aem-page-components.json` but missing
      // from `aem-component-paths`, so the dialog never got fetched. Drop
      // every (resource type, template) pair on the floor and surface the
      // gap loudly: returning the resource type so the caller can put a
      // high-visibility callout in the schema CLI summary. Logging only
      // here is too easy to miss — operators see `entries: []` in the
      // manifest and assume the discovery scanner is broken.
      logger?.error(
        `template-pages: "${resourceType}" is declared as a page-shell but missing from aem-component-paths. Add this line and re-run migrate:schema:\n    /apps/${resourceType}`,
      );
      missingComponentPaths.push(resourceType);
      continue;
    }
    excludeFromPageBuilder.add(pageComponentSanityType);

    for (const cqTemplate of entry.templates) {
      const override = entry.names?.[cqTemplate];
      let name: string;
      if (override?.name !== undefined) {
        // Pre-claimed above — reserved/collision already rejected.
        name = override.name;
      } else {
        try {
          name = templatePathToTypeName(cqTemplate);
        } catch (err) {
          logger?.warn(
            `template-pages: ${(err as Error).message} — skipping.`,
          );
          continue;
        }
        if (RESERVED_SANITY_TYPE_NAMES.has(name) || taken.has(name)) {
          name = "aem" + name.charAt(0).toUpperCase() + name.slice(1);
        }
        if (taken.has(name)) {
          const root = name;
          let suffix = 2;
          do {
            name = `${root}${suffix++}`;
          } while (taken.has(name));
        }
        taken.add(name);
      }

      const title = override?.title ?? templatePathToTitle(cqTemplate);

      // Templates with restricted components get a dedicated page-builder
      // array (base + extras) so the "+ Add" menu differs per template.
      // The document FIELD keeps the shared name — `aem-transform` writes
      // page blocks under it regardless of which array type backs it.
      const extras = templateComponents?.get(cqTemplate) ?? [];
      let builderTypeName = pageBuilderTypeName;
      if (extras.length > 0) {
        builderTypeName = `${name}Builder`;
        if (RESERVED_SANITY_TYPE_NAMES.has(builderTypeName) || taken.has(builderTypeName)) {
          const root = builderTypeName;
          let suffix = 2;
          do {
            builderTypeName = `${root}${suffix++}`;
          } while (taken.has(builderTypeName));
        }
        taken.add(builderTypeName);

        const memberByName = new Map<string, PageBuilderMember>();
        for (const m of [...baseMembers, ...extras]) {
          if (!memberByName.has(m.name)) memberByName.set(m.name, m);
        }
        const members = [...memberByName.values()].sort((a, b) =>
          a.name.localeCompare(b.name),
        );
        const builderFile = join(
          schemasDir,
          planner.relPath(builderTypeName, "object"),
        );
        await writeTextFile(
          builderFile,
          renderTemplatePageBuilder(builderTypeName, name, cqTemplate, members),
        );
        builderFiles.push(builderFile);
        builderTypeNames.push(builderTypeName);
      }

      const file = join(schemasDir, planner.relPath(name, "document"));
      const wrote = await maybeWriteTemplatePage({
        file,
        typeName: name,
        title,
        pageComponentSanityType,
        pageBuilderTypeName,
        builderTypeName,
        assetFieldType,
        logger,
      });
      if (wrote) documentFiles.push(file);

      manifest.entries.push({
        pageComponentResourceType: resourceType,
        pageComponentSanityType,
        cqTemplate,
        sanityType: name,
        sanityTitle: title,
        pageBuilderType: builderTypeName,
      });
    }
  }

  manifest.entries.sort((a, b) =>
    a.sanityType < b.sanityType ? -1 : a.sanityType > b.sanityType ? 1 : 0,
  );

  let manifestFile: string | undefined;
  if (manifestOutputDir) {
    manifestFile = join(manifestOutputDir, "cache", "page-templates.json");
    await writeJson(manifestFile, manifest);
  }

  return {
    manifestFile,
    manifest,
    excludeFromPageBuilder: Array.from(excludeFromPageBuilder),
    documentFiles,
    builderFiles,
    builderTypeNames,
    missingComponentPaths,
  };
}

interface MaybeWriteTemplatePageArgs {
  file: string;
  typeName: string;
  title: string;
  pageComponentSanityType: string;
  /** Field name for the page-builder array (shared across all page types). */
  pageBuilderTypeName: string;
  /** Array type backing the field — shared, or this template's dedicated builder. */
  builderTypeName: string;
  /** Substitute type for `featuredImage` (e.g. `bynder.asset`); unset → `image`. */
  assetFieldType?: string;
  logger?: Logger;
}

async function maybeWriteTemplatePage(
  args: MaybeWriteTemplatePageArgs,
): Promise<boolean> {
  const { file, logger } = args;
  let existing: string | undefined;
  try {
    existing = await readFile(file, "utf8");
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
  }
  if (existing !== undefined && !existing.includes(GENERATED_MARKER)) {
    logger?.info(
      `template-pages: preserving hand-authored ${file} (no GENERATED marker found)`,
    );
    return false;
  }
  await writeTextFile(file, renderTemplatePage(args));
  return true;
}

/**
 * Dedicated page-builder array for one template: the shared base members
 * plus the components the entry's `components` map restricts to this
 * template, deduped and alphabetized so the "+ Add" menu order stays
 * predictable.
 */
function renderTemplatePageBuilder(
  builderTypeName: string,
  documentTypeName: string,
  cqTemplate: string,
  members: PageBuilderMember[],
): string {
  const rendered = members
    .map(
      (m) =>
        `    defineArrayMember({ type: ${JSON.stringify(m.name)}, title: ${JSON.stringify(m.title)} }),`,
    )
    .join("\n");
  return `// ${GENERATED_MARKER}. Do not edit by hand.
// Page-builder array for the ${JSON.stringify(documentTypeName)} document type
// (AEM template ${cqTemplate}): the shared base members plus the components
// restricted to this template via the "components" map in aem-page-components.json.
import { defineArrayMember, defineType } from "sanity";

export const ${builderTypeName} = defineType({
  name: ${JSON.stringify(builderTypeName)},
  type: "array",
  of: [
${rendered}
  ],
});
`;
}

function renderTemplatePage(args: MaybeWriteTemplatePageArgs): string {
  const { typeName, title, pageComponentSanityType, pageBuilderTypeName, builderTypeName, assetFieldType } = args;
  return `// ${GENERATED_MARKER}. Safe to delete or replace.
// To author a custom document type for this AEM template, remove this file
// (or the marker comment) — the migration will not overwrite it. Custom
// types can still reference the generated ${pageBuilderTypeName} array and
// the ${pageComponentSanityType} page-properties object.
import { defineField, defineType } from "sanity";

export const ${typeName} = defineType({
  name: ${JSON.stringify(typeName)},
  title: ${JSON.stringify(title)},
  type: "document",
  // Field-groups split the document form into tabs. \`content\` is the
  // default authoring surface (title, slug, body); \`pageProperties\` holds
  // the AEM page-shell dialog values lifted from \`jcr:content\` plus the
  // \`cq:template\` traceback. Keeps the editor uncluttered when the page
  // dialog has a long tail of technical settings (\`pwaOrientation\`,
  // \`disableCache\`, \`pinPage\`, …).
  groups: [
    { name: "content", title: "Content", default: true },
    { name: "pageProperties", title: "Page properties" },
  ],
  preview: {
    select: {
      title: "title",
      slug: "slug.current",
    },
    prepare({ title, slug }) {
      return {
        title:
          typeof title === "string" && title.trim() ? title.trim() : "Untitled page",
        subtitle:
          typeof slug === "string" && slug.trim() ? "/" + slug.trim() : undefined,
      };
    },
  },
  fields: [
    defineField({
      name: "title",
      type: "string",
      group: "content",
      validation: (r) => r.required(),
    }),
    defineField({
      name: "slug",
      type: "slug",
      group: "content",
      options: { source: "title", maxLength: 96 },
      validation: (r) => r.required(),
    }),
    // Lifted from AEM \`jcr:content/cq:tags\` by \`aem-transform\` and resolved
    // through the categories manifest from \`aem-tags\`. Remove this field if
    // the migration source has no page-level tags.
    defineField({
      name: "tags",
      type: "array",
      group: "content",
      of: [{ type: "reference", to: [{ type: "category" }] }],
    }),
    // Lifted from AEM \`jcr:content/cq:featuredimage\` by \`aem-transform\` —
    // the DAM reference is rewritten to a linked asset by \`aem-assets\`.
    defineField({ name: "featuredImage", type: ${JSON.stringify(assetFieldType ?? "image")}, group: "content" }),
    defineField({
      name: ${JSON.stringify(pageBuilderTypeName)},
      type: ${JSON.stringify(builderTypeName)},
      group: "content",
    }),
    // Page-properties dialog lifted from the page-shell component's
    // \`cq:dialog\` and applied to authored values on \`jcr:content\`.
    defineField({
      name: "pageProperties",
      title: "Page properties",
      type: ${JSON.stringify(pageComponentSanityType)},
      group: "pageProperties",
    }),
    // AEM \`cq:template\` path, retained for traceability and to let scripts
    // filter pages by template after migration. Hidden by default in the
    // Studio — remove the \`hidden\` flag if authors should see it.
    defineField({
      name: "cqTemplate",
      type: "string",
      group: "pageProperties",
      readOnly: true,
      hidden: true,
    }),
  ],
});
`;
}
